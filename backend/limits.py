"""资源边界阈值（审查 F-07 修复）。

集中定义，所有上传/导入/合并/恢复接口共用；操作手册中同步记录。
可按现场需要调整，调整后重启程序生效。
"""

# 单文件上传上限（字节）：800 MB
MAX_FILE_SIZE = 800 * 1024 * 1024

# 单批上传文件数上限（文件夹上传 / 合并备份）
MAX_BATCH_FILES = 500

# Excel 导入最大数据行数（表头之后）
MAX_IMPORT_ROWS = 10_000

# 备份包/归档包解压总量上限（字节）：60 GB。
# 项目设计容量为 50GB 附件，5GB 会让本工具生成的完整备份无法恢复；仍通过
# ZIP 成员数、路径校验和落位前磁盘空间检查防范解压炸弹。
MAX_EXTRACT_TOTAL = 60 * 1024 * 1024 * 1024

# ZIP 成员数量上限：防止大量零字节成员耗尽内存、文件句柄和解压时间
MAX_ARCHIVE_MEMBERS = 20_000


def human_size(n: int) -> str:
    """字节数 → 人类可读（提示语用）。"""
    if n >= 1024 * 1024 * 1024:
        return f"{n / 1024 / 1024 / 1024:.1f} GB"
    if n >= 1024 * 1024:
        return f"{n / 1024 / 1024:.0f} MB"
    if n >= 1024:
        return f"{n / 1024:.0f} KB"
    return f"{n} B"
